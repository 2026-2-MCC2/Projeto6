-- TrocaTicket - banco de dados (PostgreSQL / Supabase)
-- Grupo Ticketudo
--
-- Baseado no DER do projeto (usuario, evento, local, categoria, ingresso,
-- pedido, item_pedido e pagamento) com as tabelas que o fluxo do site pede:
-- lotes com teto de revenda, fornecedores, credenciamento, servicos,
-- solicitacoes e o chat.
--
-- Nao precisa rodar na mao: de dentro do backend, `npm run db:reset` apaga
-- tudo, roda este arquivo e depois o seed.sql. Se preferir, da pra colar o
-- conteudo no SQL Editor do Supabase.

-- as colunas de data nao guardam fuso, entao o now() do banco precisa
-- estar no horario de Brasilia. Fica gravado no banco pra valer em qualquer
-- conexao, inclusive pela porta 6543 do Supabase.
ALTER DATABASE postgres SET timezone TO 'America/Sao_Paulo';

DROP TABLE IF EXISTS
  mensagem, chat_participante, chat, pagamento, item_pedido, pedido,
  ingresso, solicitacao_servico, fornecedor_externo, lote, evento,
  local_evento, organizador_categoria, categoria, servico, credenciamento,
  fornecedor_atuacao, fornecedor, organizador, usuario
  CASCADE;

-- --------------------------------------------------------
-- Pessoas
-- --------------------------------------------------------

CREATE TABLE usuario (
  id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(120) NOT NULL,
  email      VARCHAR(160) NOT NULL UNIQUE,
  cpf        VARCHAR(14)  NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  telefone   VARCHAR(20),
  tipo       VARCHAR(30)
                CHECK (tipo IN ('comprador','organizador','fornecedor','adm')) NOT NULL DEFAULT 'comprador',
  criado_em  TIMESTAMP NOT NULL DEFAULT current_timestamp,
  -- e-mail sempre em minusculas (o login compara sem diferenciar maiusculas)
  CONSTRAINT ck_usuario_email_minusculo CHECK (email = lower(email))
);

-- --------------------------------------------------------
-- Organizadores, fornecedores e credenciamento
-- --------------------------------------------------------
-- A conta funciona logo depois do cadastro, mas organizador e fornecedor so
-- operam de verdade depois que o adm aprova o credenciamento. A linha em
-- organizador / fornecedor nasce quando a pessoa envia o credenciamento;
-- sem linha, a situacao e "nao_solicitado".

CREATE TABLE organizador (
  id_organizador   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario       INT NOT NULL UNIQUE,
  -- fisica = produtor independente (usa o CPF da conta); juridica = produtora
  tipo_pessoa      VARCHAR(10) CHECK (tipo_pessoa IN ('fisica','juridica')) NOT NULL,
  nome_organizacao VARCHAR(140) NOT NULL,
  razao_social     VARCHAR(160),
  cnpj             VARCHAR(14) UNIQUE,
  cidade           VARCHAR(80)  NOT NULL,
  estado           CHAR(2)      NOT NULL,
  telefone         VARCHAR(20)  NOT NULL,
  descricao        TEXT NOT NULL,
  link             VARCHAR(200),
  publico_medio    INT CHECK (publico_medio > 0),
  -- espelha o ultimo credenciamento, pra nao ter que varrer o historico
  situacao         VARCHAR(30)
                   CHECK (situacao IN ('nao_solicitado','em_analise','credenciado','recusado'))
                   NOT NULL DEFAULT 'em_analise',
  criado_em        TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT ck_organizador_juridica
    CHECK (tipo_pessoa = 'fisica' OR (cnpj IS NOT NULL AND razao_social IS NOT NULL)),
  CONSTRAINT fk_organizador_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE fornecedor (
  id_fornecedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario    INT NOT NULL UNIQUE,
  nome_empresa  VARCHAR(140) NOT NULL,
  razao_social  VARCHAR(160),
  cnpj          VARCHAR(18)  NOT NULL UNIQUE,
  cidade        VARCHAR(80),
  estado        CHAR(2),
  telefone      VARCHAR(20),
  descricao     TEXT,
  link          VARCHAR(200),
  -- espelha o ultimo credenciamento, pra nao ter que varrer o historico
  situacao      VARCHAR(30)
                CHECK (situacao IN ('nao_solicitado','em_analise','credenciado','recusado'))
                NOT NULL DEFAULT 'nao_solicitado',
  criado_em     TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_fornecedor_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

-- em que areas o fornecedor atua (as mesmas dos itens de custo do evento)
CREATE TABLE fornecedor_atuacao (
  id_fornecedor INT NOT NULL,
  categoria     VARCHAR(30)
                CHECK (categoria IN ('iluminacao','comida','bebida','seguranca','estrutura','outros'))
                NOT NULL,
  PRIMARY KEY (id_fornecedor, categoria),
  CONSTRAINT fk_atuacao_fornecedor FOREIGN KEY (id_fornecedor)
    REFERENCES fornecedor (id_fornecedor) ON DELETE CASCADE
);

-- um pedido por envio: guarda quem analisou, quando e o motivo da recusa.
-- E de um organizador OU de um fornecedor, nunca dos dois.
CREATE TABLE credenciamento (
  id_credenciamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fornecedor  INT NULL,
  id_organizador INT NULL,
  id_adm         INT NULL,
  status         VARCHAR(30)
                 CHECK (status IN ('em_analise','aprovado','recusado')) NOT NULL DEFAULT 'em_analise',
  observacao     TEXT,
  solicitado_em  TIMESTAMP NOT NULL DEFAULT current_timestamp,
  revisado_em    TIMESTAMP NULL,
  CONSTRAINT ck_credenciamento_um_perfil
    CHECK ((id_fornecedor IS NULL) <> (id_organizador IS NULL)),
  CONSTRAINT fk_credenciamento_fornecedor FOREIGN KEY (id_fornecedor)
    REFERENCES fornecedor (id_fornecedor) ON DELETE CASCADE,
  CONSTRAINT fk_credenciamento_organizador FOREIGN KEY (id_organizador)
    REFERENCES organizador (id_organizador) ON DELETE CASCADE,
  CONSTRAINT fk_credenciamento_adm FOREIGN KEY (id_adm)
    REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

CREATE TABLE servico (
  id_servico    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fornecedor INT NOT NULL,
  nome          VARCHAR(140) NOT NULL,
  descricao     TEXT,
  preco         DECIMAL(10,2) NOT NULL,
  ativo         BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em     TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_servico_fornecedor FOREIGN KEY (id_fornecedor)
    REFERENCES fornecedor (id_fornecedor) ON DELETE CASCADE
);

-- --------------------------------------------------------
-- Eventos
-- --------------------------------------------------------

CREATE TABLE categoria (
  id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR(80) NOT NULL UNIQUE
);

-- tipos de evento que o organizador declarou no credenciamento
CREATE TABLE organizador_categoria (
  id_organizador INT NOT NULL,
  id_categoria   INT NOT NULL,
  PRIMARY KEY (id_organizador, id_categoria),
  CONSTRAINT fk_orgcat_organizador FOREIGN KEY (id_organizador)
    REFERENCES organizador (id_organizador) ON DELETE CASCADE,
  CONSTRAINT fk_orgcat_categoria FOREIGN KEY (id_categoria)
    REFERENCES categoria (id_categoria)
);

-- O organizador digita o local ao cadastrar o evento. A tabela existe
-- porque o mesmo lugar se repete entre eventos; a chave abaixo faz o
-- segundo evento no mesmo endereco reaproveitar a linha em vez de
-- duplicar.
CREATE TABLE local_evento (
  id_local INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome     VARCHAR(140) NOT NULL,
  cidade   VARCHAR(80)  NOT NULL,
  estado   CHAR(2)      NOT NULL,
  endereco VARCHAR(200) NOT NULL,
  CONSTRAINT uq_local UNIQUE (nome, cidade, estado)
);

CREATE TABLE evento (
  id_evento      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizador INT NOT NULL,
  id_local       INT NOT NULL,
  id_categoria   INT NOT NULL,
  nome           VARCHAR(160) NOT NULL,
  descricao      TEXT,
  data_hora      TIMESTAMP NOT NULL,
  -- o evento so fica publico depois que um adm aprova
  status         VARCHAR(30)
                CHECK (status IN ('rascunho','em_analise','aprovado','recusado'))
                 NOT NULL DEFAULT 'rascunho',
  motivo_recusa  TEXT,
  id_adm_revisor INT NULL,
  revisado_em    TIMESTAMP NULL,
  criado_em      TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_evento_organizador FOREIGN KEY (id_organizador)
    REFERENCES usuario (id_usuario),
  CONSTRAINT fk_evento_local FOREIGN KEY (id_local)
    REFERENCES local_evento (id_local),
  CONSTRAINT fk_evento_categoria FOREIGN KEY (id_categoria)
    REFERENCES categoria (id_categoria),
  CONSTRAINT fk_evento_adm FOREIGN KEY (id_adm_revisor)
    REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

-- O lote cruza os dois eixos de venda:
--   setor = onde a pessoa fica  (pista, camarote, cadeira inferior)
--   nome  = a fase da venda     (1o lote, 2o lote, ultima chamada)
-- Entao "Pista / 2o lote" e uma linha, com o seu proprio preco, a sua
-- quantidade e a janela de dias em que fica a venda.
CREATE TABLE lote (
  id_lote        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento      INT NOT NULL,
  setor          VARCHAR(60) NOT NULL,
  nome           VARCHAR(80) NOT NULL,
  preco          DECIMAL(10,2) NOT NULL,
  quantidade     INT NOT NULL,
  data_inicio    TIMESTAMP NOT NULL,
  data_fim       TIMESTAMP NOT NULL,
  -- teto de revenda em %: um lote de 100 com margem 20 so pode ser
  -- revendido ate 120. zero trava a revenda no preco original.
  margem_revenda DECIMAL(5,2) NOT NULL DEFAULT 0,
  criado_em      TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_lote_evento FOREIGN KEY (id_evento)
    REFERENCES evento (id_evento) ON DELETE CASCADE,
  CONSTRAINT uq_lote UNIQUE (id_evento, setor, nome),
  CONSTRAINT ck_lote_preco CHECK (preco >= 0),
  CONSTRAINT ck_lote_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_lote_margem CHECK (margem_revenda >= 0),
  CONSTRAINT ck_lote_janela CHECK (data_fim > data_inicio)
);

-- fornecedor particular do organizador, sem conta no site.
-- serve pro adm somar o custo do evento na hora de aprovar.
CREATE TABLE fornecedor_externo (
  id_fornecedor_externo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento INT NOT NULL,
  nome      VARCHAR(140) NOT NULL,
  servico   VARCHAR(140) NOT NULL,
  valor     DECIMAL(10,2) NOT NULL,
  contato   VARCHAR(140),
  CONSTRAINT fk_externo_evento FOREIGN KEY (id_evento)
    REFERENCES evento (id_evento) ON DELETE CASCADE
);

CREATE TABLE solicitacao_servico (
  id_solicitacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento      INT NOT NULL,
  id_servico     INT NOT NULL,
  mensagem       TEXT,
  valor_proposto DECIMAL(10,2),
  -- aguardando_organizador = pedido de organizador ainda nao credenciado.
  -- Fica retido (sem chat, o fornecedor nao ve) ate o adm aprovar o organizador.
  status         VARCHAR(30)
                CHECK (status IN ('aguardando_organizador','em_analise','aceita','recusada'))
                NOT NULL DEFAULT 'em_analise',
  criado_em      TIMESTAMP NOT NULL DEFAULT current_timestamp,
  respondido_em  TIMESTAMP NULL,
  CONSTRAINT fk_solicitacao_evento FOREIGN KEY (id_evento)
    REFERENCES evento (id_evento) ON DELETE CASCADE,
  CONSTRAINT fk_solicitacao_servico FOREIGN KEY (id_servico)
    REFERENCES servico (id_servico),
  CONSTRAINT uq_solicitacao UNIQUE (id_evento, id_servico)
);

-- --------------------------------------------------------
-- Ingressos, pedidos e pagamento
-- --------------------------------------------------------

CREATE TABLE ingresso (
  id_ingresso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento   INT NOT NULL,
  id_lote     INT NOT NULL,
  -- dono atual. no comeco e o organizador; depois de vendido passa
  -- pro comprador, que por sua vez pode anunciar a revenda.
  id_vendedor INT NOT NULL,
  setor       VARCHAR(60),
  tipo        VARCHAR(40),
  codigo      VARCHAR(40) NOT NULL UNIQUE,
  status      VARCHAR(30)
                CHECK (status IN ('disponivel','vendido','a_venda','usado','cancelado'))
              NOT NULL DEFAULT 'disponivel',
  preco       DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_ingresso_evento FOREIGN KEY (id_evento)
    REFERENCES evento (id_evento) ON DELETE CASCADE,
  CONSTRAINT fk_ingresso_lote FOREIGN KEY (id_lote)
    REFERENCES lote (id_lote) ON DELETE CASCADE,
  CONSTRAINT fk_ingresso_vendedor FOREIGN KEY (id_vendedor)
    REFERENCES usuario (id_usuario)
);

CREATE TABLE pedido (
  id_pedido    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_comprador INT NOT NULL,
  data_pedido  TIMESTAMP NOT NULL DEFAULT current_timestamp,
  valor_total  DECIMAL(10,2) NOT NULL,
  status       VARCHAR(30)
                CHECK (status IN ('aguardando_pagamento','pago','cancelado'))
               NOT NULL DEFAULT 'aguardando_pagamento',
  CONSTRAINT fk_pedido_comprador FOREIGN KEY (id_comprador)
    REFERENCES usuario (id_usuario)
);

-- o mesmo ingresso aparece aqui uma vez por venda, com o preco daquela
-- venda. e o historico de revenda do ingresso.
CREATE TABLE item_pedido (
  id_pedido      INT NOT NULL,
  id_ingresso    INT NOT NULL,
  preco_unitario DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id_pedido, id_ingresso),
  CONSTRAINT fk_item_pedido FOREIGN KEY (id_pedido)
    REFERENCES pedido (id_pedido) ON DELETE CASCADE,
  CONSTRAINT fk_item_ingresso FOREIGN KEY (id_ingresso)
    REFERENCES ingresso (id_ingresso)
);

CREATE TABLE pagamento (
  id_pagamento   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido      INT NOT NULL,
  metodo         VARCHAR(30)
                CHECK (metodo IN ('pix','cartao','boleto')) NOT NULL,
  status         VARCHAR(30)
                CHECK (status IN ('pendente','aprovado','recusado')) NOT NULL DEFAULT 'pendente',
  valor          DECIMAL(10,2) NOT NULL,
  data_pagamento TIMESTAMP NULL,
  CONSTRAINT fk_pagamento_pedido FOREIGN KEY (id_pedido)
    REFERENCES pedido (id_pedido) ON DELETE CASCADE
);

-- --------------------------------------------------------
-- Chat
-- --------------------------------------------------------

-- Um chat nasce de duas formas: preso a uma solicitacao de servico
-- (organizador e fornecedor negociando), ou aberto pelo administrador
-- direto com um usuario. No segundo caso id_solicitacao fica nulo e o
-- assunto diz do que se trata.
CREATE TABLE chat (
  id_chat        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitacao INT NULL UNIQUE,
  assunto        VARCHAR(140) NULL,
  criado_em      TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_chat_solicitacao FOREIGN KEY (id_solicitacao)
    REFERENCES solicitacao_servico (id_solicitacao) ON DELETE CASCADE
);

CREATE TABLE chat_participante (
  id_chat    INT NOT NULL,
  id_usuario INT NOT NULL,
  PRIMARY KEY (id_chat, id_usuario),
  CONSTRAINT fk_participante_chat FOREIGN KEY (id_chat)
    REFERENCES chat (id_chat) ON DELETE CASCADE,
  CONSTRAINT fk_participante_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE mensagem (
  id_mensagem    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_chat        INT NOT NULL,
  id_remetente   INT NOT NULL,
  texto_mensagem TEXT NOT NULL,
  criado_em      TIMESTAMP NOT NULL DEFAULT current_timestamp,
  CONSTRAINT fk_mensagem_chat FOREIGN KEY (id_chat)
    REFERENCES chat (id_chat) ON DELETE CASCADE,
  CONSTRAINT fk_mensagem_remetente FOREIGN KEY (id_remetente)
    REFERENCES usuario (id_usuario)
);

-- --------------------------------------------------------
-- Indices de apoio as consultas mais usadas
